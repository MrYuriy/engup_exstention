let EXT_LANG = "en";

// Resolve and cache the UI language from the stored native language.
async function extI18nInit() {
  try {
    const { native_language } = await chrome.storage.local.get("native_language");
    if (native_language && EXT_STRINGS[native_language]) EXT_LANG = native_language;
  } catch {
    /* storage unavailable (rare) — keep English */
  }
  return EXT_LANG;
}

// extT(key, params?) -> localized string; English is the fallback.
function extT(key, params) {
  const table = EXT_STRINGS[EXT_LANG] || EXT_STRINGS.en;
  let s = table[key] ?? EXT_STRINGS.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

// Translate popup elements carrying data-i18n / data-i18n-placeholder.
function extApplyI18n(root) {
  root = root || document;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = extT(el.getAttribute("data-i18n"));
  for (const el of root.querySelectorAll("[data-i18n-placeholder]"))
    el.setAttribute("placeholder", extT(el.getAttribute("data-i18n-placeholder")));
}
